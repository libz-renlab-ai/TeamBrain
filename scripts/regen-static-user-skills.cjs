#!/usr/bin/env node
// Regenerate packages/core/src/static-user-skills/content.ts from .claude/skills/<name>/SKILL.md.
//
// The generated content.ts is the single source of inline string constants
// `teamagent init` ships to `~/.claude/skills/<name>/SKILL.md` and
// `~/.codex/skills/<name>/SKILL.md`.
//
// Freshness is enforced by `packages/cli/src/__tests__/static-user-skills-freshness.test.ts`:
// CI fails if any inline string drifts from the corresponding repo file.
//
// Usage:
//   node scripts/regen-static-user-skills.cjs

const fs = require("node:fs");
const path = require("node:path");

const SKILLS = [
  "grill-me",
  "grill-via-web",
  "fixed-flow-driver",
  "claim-to-merge",
];

const ROOT = path.resolve(__dirname, "..");
const OUT = path.resolve(
  ROOT,
  "packages/core/src/static-user-skills/content.ts",
);

const entries = SKILLS.map((name) => {
  const src = path.join(ROOT, ".claude", "skills", name, "SKILL.md");
  if (!fs.existsSync(src)) {
    console.error(`MISSING source: ${src}`);
    process.exit(1);
  }
  const content = fs.readFileSync(src, "utf8");
  return `  ${JSON.stringify(name)}: ${JSON.stringify(content)},`;
}).join("\n");

const ts = `// AUTO-GENERATED by scripts/regen-static-user-skills.cjs.
// Source: .claude/skills/<name>/SKILL.md.
// Regenerate: node scripts/regen-static-user-skills.cjs
// Do not edit by hand; freshness is enforced by
// packages/cli/src/__tests__/static-user-skills-freshness.test.ts.

import type { StaticUserSkillName } from "./types.js";

export const STATIC_USER_SKILL_CONTENT: Record<StaticUserSkillName, string> = {
${entries}
};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, ts);
console.log(`Wrote ${SKILLS.length} skills to ${OUT}`);
